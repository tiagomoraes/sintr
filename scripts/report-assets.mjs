// The report's embedded assets: the three fonts of the design system and the
// window light of page 1, written as base64 into
// packages/core/src/report/assets.generated.ts, so the PDF renderer needs no
// file path at runtime (the web app bundles @sintr/core).
//
//   node scripts/report-assets.mjs          regenerate the module
//   node scripts/report-assets.mjs --light  first render the light again
//
// The light is the app's own WindowLight (packages/ui) at its morning colors,
// rendered once to an opaque JPEG: blur, masks and blend modes are read
// differently by each PDF viewer, a flat image looks the same everywhere.
