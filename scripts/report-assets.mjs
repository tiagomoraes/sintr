async function renderLight() {
  const require = createRequire(path("packages/core/package.json"));
  const { chromium } = require("playwright-core");
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 416, height: 368 }, deviceScaleFactor: 2.5 });
    await page.setContent(LIGHT_PAGE);
    const jpeg = await page.locator(".box").screenshot({ type: "jpeg", quality: 82 });
    writeFileSync(LIGHT, jpeg);
    console.log(`report assets: wrote packages/core/assets/report-light.jpg (${jpeg.length} bytes)`);
  } finally {
    await browser.close();
  }
}

/** The module's text, from the files on disk. Exported for the drift test. */
export function generatedModule() {
  const b64 = (relative) => readFileSync(path(relative)).toString("base64");
  const assets = {
    serifRoman: b64("packages/ui/fonts/source-serif-4-roman.woff2"),
    serifItalic: b64("packages/ui/fonts/source-serif-4-italic.woff2"),
    sans: b64("packages/ui/fonts/hanken-grotesk.woff2"),
    light: readFileSync(LIGHT).toString("base64"),
  };
  const lines = Object.entries(assets).map(([key, value]) => `  ${key}: "${value}",`);
  return [
    "// Generated by scripts/report-assets.mjs (make report-assets). Do not edit.",
    "// The design system's fonts (SIL OFL 1.1, packages/ui/fonts/OFL.txt) and the",
    "// window light of page 1, embedded so the PDF renderer reads no files.",
    "export const REPORT_ASSETS = {",
    ...lines,
    "} as const;",
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes("--light")) await renderLight();
  writeFileSync(OUT, generatedModule());
  console.log("report assets: wrote packages/core/src/report/assets.generated.ts");
}
